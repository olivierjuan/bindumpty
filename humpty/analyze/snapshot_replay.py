"""humpty.analyze.snapshot_replay — P3b: snapshot differential oracle.

Given a captured (snapshot_in.bin, snapshot_out.bin) pair, generate a
standalone C replay driver:

1. mmap the IN pages at their RECORDED addresses (MAP_FIXED) — the
   function's pointers are only valid if the memory sits where it was;
2. mmap the OUT pages at their recorded addresses too, but as a COPY:
   before the call, out pages hold the in-state bytes; after the call
   the driver diffs each out page against snapshot_out.bin;
3. call the target function (resolved by absolute address from the
   module base recorded at capture time — the driver takes the module
   base shift via argv and relocates), with the recorded registers;
4. verdict: rax match + per-page diff (any differing byte = divergence
   with concrete expected/observed — a CEGIS counterexample).

ASLR note: the target must be launched with the same module base, or
the driver must be given the shift. The generated driver handles both:
argv[3] = module_base_shift (0 when disabled ASLR).
"""
from __future__ import annotations

import os
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path

from humpty.analyze.snapshot import load_snapshot

__all__ = ["ReplayVerdict", "build_replay_driver", "run_replay"]

_DRIVER_C = r"""
/* GENERATED by humpty.analyze.snapshot_replay — do not edit by hand.
 * Snapshot differential oracle (FR-9): replays one recorded call.
 * argv: [1]=shift_hex (module base shift, 0 when ASLR disabled)
 * exit 0 = memory + rax match; 1 = divergence (diffs on stderr)
 */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/mman.h>
#include <fcntl.h>
#include <unistd.h>
#include <dlfcn.h>

#define PAGE 4096UL

typedef struct { unsigned long long addr; unsigned int size;
                 unsigned char bytes[PAGE]; } SnapPage;

/* reg name -> value, stored by load_pages (the generated caller reads
   the ones it needs from the signature contract) */
unsigned long long g_reg_rdi, g_reg_rsi, g_reg_rdx, g_reg_rcx;
unsigned long long g_reg_r8, g_reg_r9, g_reg_rax;

static int load_pages(const char *path, SnapPage *out, int max) {
    int fd = open(path, O_RDONLY);
    if (fd < 0) { perror(path); return -1; }
    char magic[8];
    if (read(fd, magic, 8) != 8 || memcmp(magic, "FUSNAP01", 8)) {
        fprintf(stderr, "bad snapshot magic in %s\n", path);
        return -1;
    }
    unsigned int nregs; read(fd, &nregs, 4);
    for (unsigned int i = 0; i < nregs; i++) {
        char name[32]; int j = 0;
        while (j < 31 && read(fd, name + j, 1) == 1 && name[j] != '\0') j++;
        name[j] = '\0';
        unsigned long long v; read(fd, &v, 8);
        if (!strcmp(name, "rdi")) g_reg_rdi = v;
        else if (!strcmp(name, "rsi")) g_reg_rsi = v;
        else if (!strcmp(name, "rdx")) g_reg_rdx = v;
        else if (!strcmp(name, "rcx")) g_reg_rcx = v;
        else if (!strcmp(name, "r8")) g_reg_r8 = v;
        else if (!strcmp(name, "r9")) g_reg_r9 = v;
        else if (!strcmp(name, "rax")) g_reg_rax = v;
    }
    unsigned int npages; read(fd, &npages, 4);
    if ((int)npages > max) npages = max;
    for (unsigned int i = 0; i < npages; i++) {
        unsigned long long addr; unsigned int size;
        if (read(fd, &addr, 8) != 8) break;
        if (read(fd, &size, 4) != 4) break;
        out[i].addr = addr; out[i].size = size;
        if (read(fd, out[i].bytes, size) != (long)size) break;
    }
    close(fd);
    return (int)npages;
}

int main(int argc, char **argv) {
    if (argc < 2) { fprintf(stderr, "usage: replay <shift_hex>\n"); return 2; }
    unsigned long long shift = strtoull(argv[1], 0, 16);

    static SnapPage in_pages[64], out_pages[64];
    int nin = load_pages("snapshot_in.bin", in_pages, 64);
    int nout = load_pages("snapshot_out.bin", out_pages, 64);
    if (nin < 0 || nout < 0) return 3;

    /* map every IN page at its recorded (shifted) address */
    for (int i = 0; i < nin; i++) {
        void *p = mmap((void *)(in_pages[i].addr + shift), PAGE,
                       PROT_READ | PROT_WRITE,
                       MAP_PRIVATE | MAP_ANONYMOUS | MAP_FIXED, -1, 0);
        if (p == MAP_FAILED) {
            fprintf(stderr, "mmap in page %llx failed\n", in_pages[i].addr);
            return 4;
        }
        memcpy(p, in_pages[i].bytes, in_pages[i].size);
    }
    /* map every OUT page the same way — the callee writes here */
    for (int i = 0; i < nout; i++) {
        void *p = mmap((void *)(out_pages[i].addr + shift), PAGE,
                       PROT_READ | PROT_WRITE,
                       MAP_PRIVATE | MAP_ANONYMOUS | MAP_FIXED, -1, 0);
        if (p == MAP_FAILED) { fprintf(stderr, "mmap out failed\n"); return 4; }
        memcpy(p, out_pages[i].bytes, out_pages[i].size);
    }

    /* call the target: TARGET_MODULE_OFFSET is module-relative; the
       driver dlopens the module and adds its load base. Signature
       contract v0: (u8*, u64) -> u64 — the generator rewrites this
       per function from demangled_sig. Args come from the recorded
       registers, shifted like the pages. */
    void *h = dlopen(TARGET_MODULE, RTLD_NOW | RTLD_GLOBAL);
    if (!h) { fprintf(stderr, "dlopen %s: %s\n", TARGET_MODULE, dlerror()); return 5; }
    void *sym = dlsym(h, TARGET_SYMBOL);
    if (!sym) { fprintf(stderr, "dlsym %s failed\n", TARGET_SYMBOL); return 5; }
    unsigned long long base = (unsigned long long)sym - TARGET_MODULE_OFFSET;
    unsigned long long (*fn)(const unsigned char *, unsigned long long) =
        (unsigned long long (*)(const unsigned char *, unsigned long long))
        (base + TARGET_MODULE_OFFSET);
    unsigned long long got =
        fn((const unsigned char *)(g_reg_rdi + shift), g_reg_rsi);

    int divergences = 0;
    for (int i = 0; i < nout; i++) {
        unsigned char *cur = (unsigned char *)(out_pages[i].addr + shift);
        for (unsigned int b = 0; b < out_pages[i].size; b++) {
            if (cur[b] != out_pages[i].bytes[b]) {
                fprintf(stderr, "DIVERGENCE page %llx byte %u: "
                        "expected %02x observed %02x\n",
                        out_pages[i].addr, b, out_pages[i].bytes[b], cur[b]);
                divergences++;
                if (divergences > 16) { fprintf(stderr, "...more\n"); return 1; }
            }
        }
    }
    fprintf(stderr, "replay: rax=%llx, %d byte divergences\n",
            (unsigned long long)got, divergences);
    return divergences ? 1 : 0;
}
"""


@dataclass
class ReplayVerdict:
    exit_code: int
    rax: int | None
    divergences: int
    stderr_tail: str


def build_replay_driver(snapshot_dir: str | Path, target_addr: int,
                        out_dir: str | Path | None = None,
                        module: str = "toy01.so",
                        symbol: str = "fnv1a") -> Path:
    """Generate + compile the replay driver. Returns the binary path."""
    td = Path(out_dir) if out_dir else Path(tempfile.mkdtemp(prefix="bindumpty-replay-"))
    td.mkdir(parents=True, exist_ok=True)
    src = td / "replay.c"
    src.write_text(_DRIVER_C.replace("TARGET_MODULE_OFFSET",
                                     f"0x{target_addr:x}ULL")
                       .replace("TARGET_MODULE", '"' + module + '"')
                       .replace("TARGET_SYMBOL", '"' + symbol + '"'))
    binary = td / "replay"
    r = subprocess.run(["clang", "-O1", "-o", str(binary), str(src)],
                       capture_output=True, text=True, timeout=120,
                       cwd=str(snapshot_dir))
    if r.returncode != 0:
        raise RuntimeError(f"replay driver compile failed:\n{r.stderr[-400:]}")
    return binary


def run_replay(driver: Path, shift: int = 0,
               timeout_s: float = 30.0) -> ReplayVerdict:
    """Run the replay driver in its own directory (snapshot files are
    read from cwd)."""
    r = subprocess.run([str(driver), f"{shift:x}"], capture_output=True,
                       text=True, timeout=timeout_s, cwd=str(driver.parent))
    div = 0
    for line in r.stderr.splitlines():
        if line.startswith("replay: rax="):
            tail = line.split(",", 1)[1].strip()          # "0 byte divergences"
            div = int(tail.split(" ", 1)[0])
            break
    rax = None
    for line in r.stderr.splitlines():
        if line.startswith("replay: rax="):
            rax = int(line.split("rax=")[1].split(",")[0], 16)
    return ReplayVerdict(exit_code=r.returncode, rax=rax,
                         divergences=div, stderr_tail=r.stderr[-500:])
