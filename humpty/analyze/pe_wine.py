"""humpty.analyze.pe_wine — D4.3: Wine headless runner for Win32-dependent targets.

For functions that call into Win32 (kernel32.GetUserTickCount, heap
allocations, file I/O...) neither the direct loader (D4.1) nor Unicorn
(D4.2) can run them: the Wine runner executes the target inside a real
Windows compatibility layer on Linux.

Design:
- A generated C driver (wine_driver.c) loads the target .dll, resolves
  the export by name, calls it with input from a JSON seed file, and
  writes the result (return value + optional memory dump) to an output
  file.
- The driver is compiled once per target with x86_64-w64-mingw32-gcc
  and executed under `wine64` with WINEDEBUG=-all and a per-run
  WINEPREFIX (isolated, no GUI, no services).
- The runner is headless: no display, no D-Bus, no user interaction.
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path

__all__ = ["wine_available", "WineRunResult", "run_wine_function"]

_DRIVER_C = r"""
/* GENERATED by humpty.analyze.pe_wine — do not edit by hand.
 * Loads <DLL>, resolves <EXPORT>, reads argv[1] (JSON seed), calls the
 * function, writes argv[2] (JSON result).
 * Signature contract (v0): (const uint8_t* data, unsigned long long len)
 * -> unsigned long long.  The harness generator picks the real signature
 * per function; this driver covers the pure-byte-in/word-out shape that
 * the CEGIS loop fuzzer feeds. */
#include <windows.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef unsigned long long (*fn_u64_t)(const unsigned char *, unsigned long long);
typedef unsigned int (*fn_u32_t)(const unsigned char *, unsigned int);

static unsigned char *read_file(const char *path, unsigned long long *len) {
    FILE *f = fopen(path, "rb");
    if (!f) return NULL;
    fseek(f, 0, SEEK_END);
    long sz = ftell(f);
    fseek(f, 0, SEEK_SET);
    unsigned char *buf = (unsigned char *)malloc(sz ? sz : 1);
    if (fread(buf, 1, sz, f) != (size_t)sz) { fclose(f); free(buf); return NULL; }
    fclose(f);
    *len = (unsigned long long)sz;
    return buf;
}

int main(int argc, char **argv) {
    if (argc < 3) { fprintf(stderr, "usage: driver <seed> <out>\n"); return 2; }
    unsigned long long len = 0;
    unsigned char *data = read_file(argv[1], &len);
    if (!data) { fprintf(stderr, "cannot read seed\n"); return 3; }

    HMODULE h = LoadLibraryA("<DLL>");
    if (!h) { fprintf(stderr, "LoadLibrary failed: %lu\n", GetLastError()); return 4; }
    FARPROC p = GetProcAddress(h, "<EXPORT>");
    if (!p) { fprintf(stderr, "export not found\n"); return 5; }

    /* interpret the export's real return width from the generated constant */
    unsigned long long ret;
#if RET_WIDTH == 64
    ret = ((fn_u64_t)p)(data, len);
#else
    ret = (unsigned long long)((fn_u32_t)p)(data, (unsigned int)len);
#endif
    FILE *out = fopen(argv[2], "w");
    if (!out) return 6;
    fprintf(out, "{\"ret\": %llu, \"len\": %llu}\n",
            (unsigned long long)ret, len);
    fclose(out);
    free(data);
    return 0;
}
"""


@dataclass
class WineRunResult:
    ret: int | None          # function return value (u64)
    exit_code: int           # driver exit code (0 = ok)
    stderr: str              # tail of Wine's stderr for diagnosis
    duration_s: float


def wine_available() -> bool:
    """True when wine and a mingw cross-compiler can be executed."""
    return wine_binary() is not None and shutil.which("x86_64-w64-mingw32-gcc") is not None


def wine_binary() -> str | None:
    """Locate a wine launcher: PATH first, then Debian's /usr/lib/wine."""
    w = shutil.which("wine64") or shutil.which("wine")
    if w:
        return w
    for cand in ("/usr/lib/wine/wine64", "/usr/lib/wine/wine"):
        if os.path.isfile(cand) and os.access(cand, os.X_OK):
            return cand
    return None


def run_wine_function(pe_path: str | Path, export: str,
                      seed: bytes, *, ret_width: int = 64,
                      workdir: str | Path | None = None,
                      timeout_s: float = 60.0) -> WineRunResult:
    """Run one exported PE function under Wine, headless.

    Compiles a per-target driver with mingw, runs it under wine64 with an
    isolated WINEPREFIX, and returns the parsed result. Raises RuntimeError
    with the Wine stderr tail when the driver fails.
    """
    if not wine_available():
        raise RuntimeError("wine64/x86_64-w64-mingw32-gcc not on PATH (D4.3)")

    pe_path = Path(pe_path).resolve()
    td = Path(workdir) if workdir else Path(tempfile.mkdtemp(prefix="bindumpty-wine-"))
    td.mkdir(parents=True, exist_ok=True)

    # stage the dll: driver loads it by name from its own directory
    dll = td / pe_path.name
    shutil.copy2(pe_path, dll)

    driver_c = td / "wine_driver.c"
    driver_c.write_text(_DRIVER_C
                        .replace("<DLL>", pe_path.name)
                        .replace("<EXPORT>", export)
                        .replace("RET_WIDTH == 64", f"RET_WIDTH == {ret_width}"))

    driver_exe = td / "wine_driver.exe"
    cc = ["x86_64-w64-mingw32-gcc", "-O1", "-o", str(driver_exe),
          str(driver_c)]
    r = subprocess.run(cc, capture_output=True, text=True, timeout=120)
    if r.returncode != 0:
        raise RuntimeError(f"mingw driver compile failed:\n{r.stderr[-400:]}")

    seed_f = td / "seed.bin"
    seed_f.write_bytes(seed)
    out_f = td / "out.json"

    env = dict(os.environ,
               WINEDEBUG="-all",
               WINEPREFIX=str(td / "prefix"),
               WINEDLLOVERRIDES="mscoree,mshtml=",  # skip mono/gecko prompts
               DISPLAY="")                          # headless
    import time
    t0 = time.monotonic()
    try:
        r = subprocess.run([wine_binary(), str(driver_exe), str(seed_f), str(out_f)],
                           capture_output=True, text=True, timeout=timeout_s,
                           env=env, cwd=str(td))
        exit_code, stderr = r.returncode, r.stderr[-500:]
    except subprocess.TimeoutExpired:
        exit_code, stderr = -1, "wine timeout"
    dur = time.monotonic() - t0

    ret = None
    if out_f.exists():
        try:
            ret = json.loads(out_f.read_text())["ret"]
        except (json.JSONDecodeError, KeyError):
            ret = None
    return WineRunResult(ret=ret, exit_code=exit_code, stderr=stderr,
                         duration_s=dur)
