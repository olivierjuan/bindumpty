"""M1 CEGIS loop (FR-4, FR-5, FR-15, NFR-6) — orchestrates one leaf.

  for iteration in 1..K:
      src = develop(spec, counterexample)   # the agent runtime (FR-4)
      write_candidate(src)                  # rebuild the candidate .so
      result = run_fuzz(budget)             # differential fuzzing (FR-6)
      if not result.divergent: TRUSTED      # budget exhausted clean
      counterexample = dedup(result.counterexamples)  # FR-15
  FAILED                                    # K exhausted

The develop function is injected: `stub_develop` (deterministic, LLM-free —
switches on the known seed bug) for CI; `pydantic_develop`
(horses/spikes/spike_s4.py) is the real runtime once the gateway answers.

Counterexample management (FR-15): distinct divergent inputs are persisted to
horses/corpus/m1/counterexamples/ and replayed (deterministically, NFR-2)
before every fuzz round — a regression suite the fixer must survive.

Cost cap (NFR-6): max_iter bounds LLM round-trips; each is one candidate.
"""
from __future__ import annotations

import os
import sys
import time
from dataclasses import dataclass, field

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import harness_driver as hd  # noqa: E402

ROOT = hd.ROOT
CE_DIR = os.path.join(hd.CORPUS, "counterexamples")

GOOD_SRC = """/* horse_candidate.c — generated by the M1 CEGIS loop */
#include <stdint.h>
#include <stddef.h>

uint32_t fnv1a(const uint8_t *data, size_t len) {
    uint32_t hash = 2166136261u;
    for (size_t i = 0; i < len; i++) {
        hash ^= (uint32_t)data[i];
        hash *= 16777619u;
    }
    return hash;
}
"""


@dataclass
class CegisResult:
    leaf: str
    verified: bool
    iterations: int
    counterexamples: list = field(default_factory=list)
    total_wall_s: float = 0.0
    history: list = field(default_factory=list)


# --- develop runtimes (FR-4, swappable) --------------------------------------

def stub_develop(spec, counterexample: str | None = None) -> str:
    """LLM-free stand-in: knows the fix for the seed bug. Verifies the loop
    plumbing end to end without a live model (CI-safe)."""
    if counterexample is None:
        return open(os.path.join(ROOT, "horses", "src", "horse_candidate.c")).read()
    return GOOD_SRC


def make_pydantic_develop(model: str | None = None):
    """The real runtime. Import lazily so the module works without the
    gateway. Returns a develop(spec, counterexample) -> str function."""
    sys.path.insert(0, os.path.join(ROOT, "horses", "spikes"))
    import s4_core
    import spike_s4

    def develop(spec, counterexample: str | None = None) -> str:
        prompt = s4_core.develop_prompt(spec, counterexample)
        res = spike_s4.pydantic_develop(spec, counterexample, model=model)
        if res.error:
            raise RuntimeError(f"develop failed: {res.error}")
        return res.source

    return develop


# --- counterexample persistence (FR-15): canonical store is harness_driver --

CE_DIR = hd.CE_DIR
ce_path = hd.ce_path
persist_counterexample = hd.persist_counterexample
load_counterexamples = hd.load_counterexamples


# --- the loop ----------------------------------------------------------------

def cegis_loop(spec, develop, max_iter: int = 5, fuzz_budget_s: int = 15,
               log=print) -> CegisResult:
    """One leaf through develop -> differential fuzz -> repair."""
    t0 = time.perf_counter()
    ce_data: bytes | None = None
    history: list[dict] = []

    for it in range(1, max_iter + 1):
        # 1. Replay persisted counterexamples first (FR-15 regression suite):
        #    a candidate that still fails a known one is rejected before any
        #    fuzz budget is spent on it.
        known = load_counterexamples()
        if known:
            src = develop(spec, _describe(known))
        else:
            src = develop(spec, None)

        hd.write_candidate(src)
        if known:
            still_bad = hd.run_replay(known)
            if still_bad:
                log(f"  iter {it}: REJECTED — fails {len(still_bad)} persisted "
                    f"counterexample(s)")
                history.append({"iter": it, "outcome": "rejected_regression"})
                # Feed the first failing case back and try again.
                ce_data = still_bad[0].as_input()
                continue

        # 2. Fuzz for the round's budget.
        r = hd.run_fuzz(budget_s=fuzz_budget_s)
        if not r.divergent:
            total = time.perf_counter() - t0
            log(f"  iter {it}: TRUSTED ({r.execs} execs clean)")
            history.append({"iter": it, "outcome": "trusted", "execs": r.execs})
            return CegisResult(leaf=spec.name, verified=True, iterations=it,
                               counterexamples=[], total_wall_s=total,
                               history=history)

        new = [c for c in r.counterexamples]
        first = new[0]
        added = persist_counterexample(first.as_input())
        log(f"  iter {it}: DIVERGENT — {first.describe()}"
            f"{' (new, persisted)' if added else ''}")
        history.append({"iter": it, "outcome": "divergent",
                        "ce_len": len(first.as_input())})
        ce_data = first.as_input()

    total = time.perf_counter() - t0
    return CegisResult(leaf=spec.name, verified=False, iterations=max_iter,
                       counterexamples=load_counterexamples(),
                       total_wall_s=total, history=history)


def _describe(known: list[bytes]) -> str:
    lines = [f"  input #{i}: len={len(d)} hex={d.hex()[:128]}"
             for i, d in enumerate(known)]
    return "\n".join(lines)
