# The seed bug from test_cegis_loop.py: fnv1a with a poisoned len==255 case.
# Written as full source (not a replace() into CAND_SRC) so the fixture can't
# silently no-op when the checked-in candidate's formatting drifts.
BUGGY_SRC = """\
/* horse_candidate.c — generated by the M1 CEGIS loop */
#include <stdint.h>
#include <stddef.h>

uint32_t fnv1a(const uint8_t *data, size_t len) {
    uint32_t hash = 2166136261u;
    if (len == 0xFF) hash = 0x12345678u;
    for (size_t i = 0; i < len; i++) {
        hash ^= (uint32_t)data[i];
        hash *= 16777619u;
    }
    return hash;
}
"""

# The repaired candidate the develop stub returns after the counterexample
# (same fix cegis.stub_develop returns: the textbook FNV-1a loop).
FIX_SRC = """\
/* horse_candidate.c — generated by the M1 CEGIS loop */
#include <stdint.h>
#include <stddef.h>

uint32_t fnv1a(const uint8_t *data, size_t len) {
    uint32_t hash = 2166136261u;
    for (size_t i = 0; i < len; i++) {
        hash ^= (uint32_t)data[i];
        hash *= 16777619u;
    }
    return hash;
}
"""


@pytest.fixture()
def factory(tmp_path):
    db_url = f"sqlite:///{tmp_path}/leaf_loop.db"
    ini = Config(os.path.join(ROOT, "alembic.ini"))
    ini.set_main_option("script_location", os.path.join(ROOT, "humpty/db/alembic"))
    ini.set_main_option("sqlalchemy.url", db_url)
    eng = create_engine(db_url)
    command.upgrade(ini, "head")
    yield make_session_factory(eng)
    eng.dispose()


@pytest.fixture()
def fnv1a_function(factory, tmp_path, monkeypatch):
    """A pending fnv1a leaf row plus the buggy seed candidate on disk.

    The candidate source is redirected to tmp_path (hd.CAND_SRC plus the
    build script's CANDIDATE_SRC env): ``horses/src/horse_candidate.c`` is
    shared mutable state that other workers rewrite, so this test must not
    read or restore it — a str.replace bug injection silently no-ops when
    that file's formatting drifts, and a teardown restore races other
    writers. The develop stub reads the redirected source instead of
    ``cegis.stub_develop`` (which hardcodes the checked-in path).
    """
    sha = hashlib.sha256(b"leaf-loop").hexdigest()
    with session_scope(factory) as s:
        fn = Function(binary_sha256=sha, name="fnv1a", address=0x8000,
                      state="pending")
        s.add(fn)
        s.flush()
        fid = fn.id
    cand_src = tmp_path / "horse_candidate.c"
    cand_src.write_text(BUGGY_SRC)
    monkeypatch.setattr(hd, "CAND_SRC", str(cand_src))
    monkeypatch.setenv("CANDIDATE_SRC", str(cand_src))

    def develop(spec, counterexample=None):
        # cegis.stub_develop against the redirected source: buggy first, the
        # known fix once a counterexample exists.
        if counterexample is None:
            return cand_src.read_text()
        return FIX_SRC

    # clean the shared counterexample store (canonical store is horses/, FR-15)
    if os.path.isdir(cegis.CE_DIR):
        for f in os.listdir(cegis.CE_DIR):
            os.remove(os.path.join(cegis.CE_DIR, f))
    yield fid, develop


def test_leaf_loop_drives_fnv1a_to_trusted(factory, fnv1a_function):
    fid, develop = fnv1a_function
    with session_scope(factory) as s:
        result = run_leaf_loop(
            s, function_id=fid, develop=develop,
            max_iter=5, fuzz_budget_s=10, log=lambda *_: None)

    assert result["verified"], f"expected TRUSTED, got {result}"

    with session_scope(factory) as s:
        fn = s.get(Function, fid)
        assert fn.state == "trusted"
        # Confidence per humpty.domain.confidence: the final campaign was
        # clean, so divergences=0 and the fuzz channel scores the budget
        # actually consumed (>= 1.0 is capped at 1.0 when the harness
        # out-executed the nominal budget). This leaf saw a divergence, so a
        # perfect score is only reached by out-running the whole budget.
        assert 0.0 < fn.confidence <= 1.0

        candidates = (s.query(Candidate)
                      .filter(Candidate.function_id == fid)
                      .order_by(Candidate.id).all())
        assert len(candidates) >= 2, "expected a diverged and a repaired round"
        statuses = [c.status for c in candidates]
        assert "diverged" in statuses and "trusted" in statuses
        assert all(c.created_by == "dev" for c in candidates)

        ces = (s.query(Counterexample)
               .filter(Counterexample.function_id == fid).all())
        assert len(ces) == 1, "the seed bug has exactly one distinct divergence"
        ce = ces[0]
        assert ce.kind == "return"
        assert ce.input_sha256 == hashlib.sha256(ce.input_blob).hexdigest()
        assert ce.expected is not None and ce.observed is not None
        assert ce.expected != ce.observed
        # the known seed bug: len==255 input
        assert len(ce.input_blob) == 255

        runs = (s.query(FuzzRun)
                .join(Candidate, FuzzRun.candidate_id == Candidate.id)
                .filter(Candidate.function_id == fid).all())
        assert len(runs) >= 1
        assert all(r.engine == "libfuzzer" for r in runs)
        assert any(r.divergences == 0 for r in runs)
        divergent_runs = [r for r in runs if r.divergences > 0]
        assert divergent_runs, "the seed bug must produce a divergent campaign"

        events = (s.query(Event)
                  .filter(Event.kind.like("state:%"), Event.function_id == fid)
                  .order_by(Event.seq).all())
        chain = [e.kind for e in events]
        assert chain == [
            "state:pending:ready",
            "state:ready:fuzzing",
            "state:fuzzing:divergent",
            "state:divergent:repairing",
            "state:repairing:fuzzing",
            "state:fuzzing:trusted",
        ], f"unexpected transition chain: {chain}"


def test_leaf_loop_rejects_start_from_fuzzing(factory):
    """states.py is law: the loop refuses a row already mid-flight."""
    sha = hashlib.sha256(b"mid-flight").hexdigest()
    with session_scope(factory) as s:
        fn = Function(binary_sha256=sha, name="mid", address=0x9000,
                      state="fuzzing")
        s.add(fn)
        s.flush()
        with pytest.raises(LeafLoopError):
            run_leaf_loop(s, function_id=fn.id, develop=cegis.stub_develop,
                          max_iter=1, fuzz_budget_s=1, log=lambda *_: None)
