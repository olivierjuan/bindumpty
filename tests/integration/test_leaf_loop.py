"""Integration: the M1 king orchestrator drives a leaf end to end.

``humpty.king.leaf_loop.run_leaf_loop`` wires the proven horses/ CEGIS
mechanics to the database state machine: with the LLM-free stub develop
runtime the toy fnv1a leaf must go

    pending -> ready -> fuzzing -> divergent -> repairing -> fuzzing
            -> trusted

and persist, inside the same transaction as each state change: one Candidate
per develop round (the seed bug candidate marked diverged, the repaired one
trusted), the deduplicated Counterexample, the fuzz_runs campaigns, and the
full transition chain as events.

Skipped when the toy artifacts or the libFuzzer harness are not built
(same pattern as test_m0_exit.py / test_cegis_loop.py).
"""
